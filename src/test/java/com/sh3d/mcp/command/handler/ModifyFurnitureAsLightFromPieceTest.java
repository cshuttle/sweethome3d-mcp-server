/**
 * modify_furniture's {@code asLight: true} on a piece that came from no catalog light, such as a generated model
 * (no catalog id): the light is built from the piece itself, so it keeps the piece's id, name, model, size, angle,
 * place, level and every other property, with no point sources and Sweet Home 3D's default power. The piece wears
 * the two-material fixture model {@code two_tone.obj} ("paint" and "label").
 */
class ModifyFurnitureAsLightFromPieceTest {

    private static final float[][] IDENTITY = {{1, 0, 0}, {0, 1, 0}, {0, 0, 1}};

    private ModifyFurnitureHandler handler;
    private Home home;
    private HomeAccessor accessor;
    private URLContent twoTone;

    @BeforeEach
    void setUp() {
        handler = new ModifyFurnitureHandler();
        home = new Home();
        twoTone = new URLContent(getClass().getResource("/models/two_tone.obj"));
        accessor = createAccessorWithCatalog(home, new FurnitureCatalog());
    }

    @Test
    void testAGeneratedPieceBecomesALightKeepingEverything() {
        Level ground = addLevel(home, "Ground", 0, 250, 12);
        Level porch = addLevel(home, "Porch", 100, 250, 12);
        home.setSelectedLevel(ground);
        HomePieceOfFurniture before = generated("Before");
        HomePieceOfFurniture piece = generated("Back porch step lights");
        HomePieceOfFurniture after = generated("After");
        piece.setLevel(porch);
        piece.setX(123.5f);
        piece.setY(456.5f);
        piece.setElevation(-12.5f);
        piece.setAngle((float) Math.toRadians(30));
        piece.setWidth(300f);
        piece.setDepth(40f);
        piece.setHeight(60f);
        piece.setNameVisible(true);
        piece.setNameXOffset(7f);
        piece.setDescription("50 step lights");
        piece.setInformation("generated by step_lights.py");
        piece.setColor(0x336699);
        piece.setShininess(0.25f);
        piece.setVisible(false);
        piece.setModelMirrored(true);
        piece.setMovable(false);
        piece.setPrice(new BigDecimal("12.50"));
        piece.setProperty("ha_entity", "light.step_lights");
        piece.setProperty("houseWalk", "round 82");
        FurnitureUtil.setDropOnTopElevation(piece, -1f);
        String id = piece.getId();

        Response resp = handler.execute(request(id, "asLight", true), accessor);

        assertTrue(resp.isOk(), resp.getMessage());
        assertEquals(Boolean.TRUE, resp.getData().get("converted"));
        assertEquals(3, home.getFurniture().size());
        assertSame(before, home.getFurniture().get(0));
        assertSame(after, home.getFurniture().get(2));
        HomePieceOfFurniture now = home.getFurniture().get(1);
        assertTrue(now instanceof HomeLight, "the piece is a light now");
        HomeLight light = (HomeLight) now;
        assertEquals(id, light.getId());
        assertNull(light.getCatalogId());
        assertSame(porch, light.getLevel(), "level kept, not the selected one");
        assertSame(ground, home.getSelectedLevel());
        assertEquals("Back porch step lights", light.getName());
        assertEquals("50 step lights", light.getDescription());
        assertEquals("generated by step_lights.py", light.getInformation());
        assertEquals("house-model", light.getCreator());
        assertSame(twoTone, light.getModel(), "same model");
        assertEquals(Long.valueOf(1234L), light.getModelSize());
        assertTrue(light.isNameVisible());
        assertEquals(7f, light.getNameXOffset(), 1e-6);
        assertEquals(123.5f, light.getX(), 1e-6);
        assertEquals(456.5f, light.getY(), 1e-6);
        assertEquals(-12.5f, light.getElevation(), 1e-6);
        assertEquals(Math.toRadians(30), light.getAngle(), 1e-4);
        assertEquals(300f, light.getWidth(), 1e-6);
        assertEquals(40f, light.getDepth(), 1e-6);
        assertEquals(60f, light.getHeight(), 1e-6);
        assertEquals(Integer.valueOf(0x336699), light.getColor());
        assertEquals(0.25f, light.getShininess(), 1e-6);
        assertFalse(light.isVisible());
        assertTrue(light.isModelMirrored());
        assertFalse(light.isMovable());
        assertEquals(new BigDecimal("12.50"), light.getPrice());
        assertEquals("light.step_lights", light.getProperty("ha_entity"));
        assertEquals("round 82", light.getProperty("houseWalk"));
        assertEquals(-1f, light.getDropOnTopElevation(), 1e-6);
        // the catalog flags a piece is born with, which have no setters
        assertEquals(piece.isResizable(), light.isResizable());
        assertFalse(light.isDeformable(), "not deformable, as the piece");
        assertEquals(piece.isWidthDepthDeformable(), light.isWidthDepthDeformable());
        assertEquals(piece.isTexturable(), light.isTexturable());
        assertEquals(piece.isHorizontallyRotatable(), light.isHorizontallyRotatable());
        assertEquals(piece.getModelFlags(), light.getModelFlags());
        // no point sources, the default power, no glowing materials
        assertEquals(0, light.getLightSources().length);
        assertEquals(0.5f, light.getPower(), 1e-6);
        assertEquals(0, light.getLightSourceMaterialNames().length);
        assertEquals(50.0, ((Number) resp.getData().get("lightPower")).doubleValue(), 1e-6);
        assertEquals(Collections.emptyList(), resp.getData().get("lightSources"));
        assertEquals(Collections.emptyList(), resp.getData().get("lightSourceMaterialNames"));
    }

    @Test
    void testAPitchedPieceKeepsItsPitchAndRoll() {
        HomePieceOfFurniture piece = generated("Tilted");
        piece.setPitch(0.3f);
        piece.setRoll(0.2f);

        Response resp = handler.execute(request(piece.getId(), "asLight", true), accessor);

        assertTrue(resp.isOk(), resp.getMessage());
        HomeLight light = (HomeLight) home.getFurniture().get(0);
        assertEquals(0.3f, light.getPitch(), 1e-6);
        assertEquals(0.2f, light.getRoll(), 1e-6);
    }

    @Test
    void testConvertAndSetPowerInOneCall() {
        HomePieceOfFurniture piece = generated("Strip light");

        Response resp = handler.execute(request(piece.getId(), "asLight", true, "lightPower", 20, "x", 5.0),
                accessor);

        assertTrue(resp.isOk(), resp.getMessage());
        HomeLight light = (HomeLight) home.getFurniture().get(0);
        assertEquals(0.2f, light.getPower(), 1e-6);
        assertEquals(5f, light.getX(), 1e-6);
        assertEquals(20.0, ((Number) resp.getData().get("lightPower")).doubleValue(), 1e-6);
    }

    @Test
    void testConvertSetPowerAndGlowingMaterialsInOneCall() {
        HomePieceOfFurniture piece = generated("Back porch step lights");

        Response resp = handler.execute(request(piece.getId(), "asLight", true, "lightPower", 20,
                "lightSourceMaterialNames", Collections.singletonList("label")), accessor);

        assertTrue(resp.isOk(), resp.getMessage());
        HomeLight light = (HomeLight) home.getFurniture().get(0);
        assertEquals(piece.getId(), light.getId());
        assertArrayEquals(new String[]{"label"}, light.getLightSourceMaterialNames());
        assertEquals(0.2f, light.getPower(), 1e-6);
        assertEquals(Collections.singletonList("label"), resp.getData().get("lightSourceMaterialNames"));
    }

    @Test
    void testAnUnknownGlowingMaterialRefusesTheConversionToo() {
        HomePieceOfFurniture piece = generated("Back porch step lights");

        Response resp = handler.execute(request(piece.getId(), "asLight", true,
                "lightSourceMaterialNames", Collections.singletonList("lens")), accessor);

        assertTrue(resp.isError());
        assertTrue(resp.getMessage().contains("label, paint"), resp.getMessage());
        assertSame(piece, home.getFurniture().get(0), "not converted");
    }

    @Test
    void testLightColorOnAConvertedPieceWithNoSourcesIsRefusedAndNothingChanges() {
        HomePieceOfFurniture piece = generated("Strip light");

        Response resp = handler.execute(request(piece.getId(), "asLight", true, "lightColor", "#FFFFFF"), accessor);

        assertTrue(resp.isError());
        assertTrue(resp.getMessage().contains("no light sources"), resp.getMessage());
        assertSame(piece, home.getFurniture().get(0), "not converted");
    }

    @Test
    void testADoorOrWindowIsRefused() {
        HomeDoorOrWindow door = new HomeDoorOrWindow(new CatalogDoorOrWindow("test#door", "Door", null, null, twoTone,
                80f, 10f, 200f, 0f, true, 1f, 0f, new Sash[0], IDENTITY, null, false, null, null));
        home.addPieceOfFurniture(door);

        Response resp = handler.execute(request(door.getId(), "asLight", true), accessor);

        assertTrue(resp.isError());
        assertTrue(resp.getMessage().contains("door or window"), resp.getMessage());
        assertSame(door, home.getFurniture().get(0));
    }

    @Test
    void testTheConvertedLightSurvivesASaveAndReload(@TempDir Path dir) throws Exception {
        Level porch = addLevel(home, "Porch", 100, 250, 12);
        HomePieceOfFurniture piece = generated("Back porch step lights");
        piece.setLevel(porch);
        piece.setX(321f);
        piece.setAngle((float) Math.toRadians(90));
        piece.setProperty("ha_entity", "light.step_lights");
        handler.execute(request(piece.getId(), "asLight", true, "lightPower", 20,
                "lightSourceMaterialNames", Collections.singletonList("label")), accessor);
        String file = dir.resolve("converted.sh3d").toString();

        new HomeFileRecorder(0, false, null, false, true).writeHome(home, file);
        Home reloaded = new HomeFileRecorder(0, false, null, false, true).readHome(file);

        HomePieceOfFurniture back = reloaded.getFurniture().stream()
                .filter(p -> piece.getId().equals(p.getId())).findFirst().orElse(null);
        assertNotNull(back, "the light keeps its id");
        assertTrue(back instanceof HomeLight, "still a light");
        HomeLight light = (HomeLight) back;
        assertNull(light.getCatalogId());
        assertEquals("Back porch step lights", light.getName());
        assertEquals("Porch", light.getLevel().getName());
        assertEquals(321f, light.getX(), 1e-6);
        assertEquals(Math.toRadians(90), light.getAngle(), 1e-4);
        assertEquals(0, light.getLightSources().length);
        assertEquals(0.2f, light.getPower(), 1e-6);
        assertArrayEquals(new String[]{"label"}, light.getLightSourceMaterialNames());
        assertEquals("light.step_lights", light.getProperty("ha_entity"));
    }

    @Test
    @SuppressWarnings("unchecked")
    void testTheSchemaAndDescriptionSayAnyPieceConverts() {
        Map<String, Object> props = (Map<String, Object>) handler.getSchema().get("properties");
        String asLight = (String) ((Map<String, Object>) props.get("asLight")).get("description");

        assertTrue(asLight.contains("no catalog id"), asLight);
        assertTrue(handler.getDescription().contains("no catalog id"), handler.getDescription());
    }

    // ======================== Helpers ========================

    /**
     * A piece like a generated model: no catalog id, not deformable, a model and a creator of its own. Built with
     * the full catalog constructor so the catalog-only flags (deformable, model size, creator) differ from the
     * defaults.
     */
    private HomePieceOfFurniture generated(String name) {
        CatalogPieceOfFurniture catalogPiece = new CatalogPieceOfFurniture(null, name, null, null, null,
                null, null, null, null, twoTone, 100f, 80f, 50f, 0f, 1f, true, null, IDENTITY, 0, 1234L,
                "house-model", true, false, true, true, null, null, null, null);
        HomePieceOfFurniture piece = new HomePieceOfFurniture(catalogPiece);
        piece.setCatalogId(null);
        home.addPieceOfFurniture(piece);
        return piece;
    }

    private static Request request(String id, Object... keyValues) {
        Map<String, Object> params = new LinkedHashMap<>();
        params.put("id", id);
        for (int i = 0; i < keyValues.length; i += 2) {
            params.put((String) keyValues[i], keyValues[i + 1]);
        }
        return new Request("modify_furniture", params);
    }
}
